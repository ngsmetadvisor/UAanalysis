# @title  Tephigram + CAPE
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.ticker as ticker
from datetime import datetime, timezone

# ── thermodynamic constants ───────────────────────────────────────────────────
Rd   = 287.05    # J kg-1 K-1
Rv   = 461.5
Cp   = 1005.7
Lv   = 2.501e6
eps  = Rd / Rv   # 0.622
kd   = Rd / Cp   # 0.2854  (dry adiabatic lapse rate exponent)

P0   = 1000.0    # hPa reference pressure

# ── helper functions ──────────────────────────────────────────────────────────

def theta(T_K, p_hPa):
    """Potential temperature (K)."""
    return T_K * (P0 / p_hPa) ** kd

def es(T_K):
    """Saturation vapour pressure (hPa) — Bolton 1980."""
    T_C = T_K - 273.15
    return 6.112 * np.exp(17.67 * T_C / (T_C + 243.5))

def mixr_sat(T_K, p_hPa):
    """Saturation mixing ratio (kg/kg)."""
    e_s = es(T_K)
    return eps * e_s / (p_hPa - e_s)

def theta_e(T_K, Td_K, p_hPa):
    """Equivalent potential temperature (K) — Bolton 1980 eq 43."""
    r  = mixr_sat(Td_K, p_hPa)           # mixing ratio at dewpoint ≈ actual r
    TL = 56 + 1.0 / (1.0 / (Td_K - 56) + np.log(T_K / Td_K) / 800.0)
    return T_K * (P0 / p_hPa) ** (0.2854 * (1 - 0.28e-3 * r * 1000)) \
           * np.exp((3.376 / TL - 0.00254) * r * 1000 * (1 + 0.81e-3 * r * 1000))

def lcl(T_K, Td_K, p_hPa):
    """LCL temperature and pressure (K, hPa) — Bolton 1980."""
    TL = 56 + 1.0 / (1.0 / (Td_K - 56) + np.log(T_K / Td_K) / 800.0)
    pL = p_hPa * (TL / T_K) ** (1.0 / kd)
    return TL, pL

def moist_adiabat(T_K, p_hPa, p_top=100.0, dp=-2.0):
    """
    Follow a saturated adiabat from (T_K, p_hPa) upward.
    Returns arrays of (p, T) along the parcel path.
    """
    p_arr, T_arr = [p_hPa], [T_K]
    p = p_hPa
    T = T_K
    while p > p_top:
        p_new = p + dp
        # pseudo-adiabatic lapse rate
        r_s  = mixr_sat(T, p)
        numer = (Rd * T + Lv * r_s)
        denom = p * (Cp + Lv**2 * r_s * eps / (Rd * T**2))
        dT_dp = numer / denom          # K/hPa
        T = T + dT_dp * dp
        p = p_new
        p_arr.append(p)
        T_arr.append(T)
    return np.array(p_arr), np.array(T_arr)

def compute_cape_cin(p_arr, T_arr, Td_arr):
    """
    Surface-based CAPE and CIN (J/kg).
    Lifts surface parcel dry to LCL, then moist adiabatically to top.
    """
    # sort surface→top
    idx  = np.argsort(p_arr)[::-1]
    p    = p_arr[idx]
    T    = T_arr[idx]
    Td   = Td_arr[idx]

    # surface parcel
    T0, Td0, p0 = T[0], Td[0], p[0]
    th0  = theta(T0, p0)
    TL, pL = lcl(T0, Td0, p0)

    # parcel temperature along dry adiabat (surface → LCL)
    def parcel_dry(p_lev):
        return th0 * (p_lev / P0) ** kd

    # parcel path above LCL along moist adiabat
    p_moist, T_moist = moist_adiabat(TL, pL, p_top=max(p[-1], 100.0))

    def parcel_T(p_lev):
        if p_lev >= pL:
            return parcel_dry(p_lev)
        else:
            return float(np.interp(p_lev, p_moist[::-1], T_moist[::-1]))

    CAPE = 0.0
    CIN  = 0.0
    for i in range(len(p) - 1):
        p_mid = 0.5 * (p[i] + p[i+1])
        T_env = 0.5 * (T[i] + T[i+1])
        T_par = parcel_T(p_mid)
        # dz via hypsometric
        dz = -Rd * T_env / (9.81 * p_mid) * (p[i+1] - p[i]) * 100.0
        buoy = 9.81 * (T_par - T_env) / T_env * dz
        if buoy > 0:
            CAPE += buoy
        else:
            if CAPE == 0.0:   # still below LFC
                CIN += buoy

    return CAPE, CIN, pL, TL

def find_mu_index(p_arr, T_arr):
    """Index of the warmest level at or below 850 hPa (most-unstable source level)."""
    mask = p_arr >= 850
    if not mask.any():
        mask = np.ones_like(p_arr, dtype=bool)
    idxs = np.where(mask)[0]
    return idxs[np.argmax(T_arr[idxs])]

def compute_cape_from_level(p_arr, T_arr, Td_arr, idx0, Td_surface=None):
    """CAPE/CIN lifting a parcel from an arbitrary level (arrays already surface→top sorted).

    Td_surface: if provided, use this as the parcel's source dewpoint instead of
    Td_arr[idx0]. This matches the convention that the MU parcel is lifted from
    the warmest sub-850hPa level but should carry the actual surface moisture,
    not the dewpoint observed at that elevated level.
    """
    p, T, Td = p_arr[idx0:], T_arr[idx0:], Td_arr[idx0:]
    T0, p0 = T[0], p[0]
    Td0 = Td_surface if Td_surface is not None else Td[0]
    th0 = theta(T0, p0)
    TL, pL = lcl(T0, Td0, p0)

    def parcel_dry(p_lev):
        return th0 * (p_lev / P0) ** kd

    p_moist, T_moist = moist_adiabat(TL, pL, p_top=p[-1])

    def parcel_T(p_lev):
        if p_lev >= pL:
            return parcel_dry(p_lev)
        else:
            return float(np.interp(p_lev, p_moist[::-1], T_moist[::-1]))

    CAPE = 0.0
    CIN  = 0.0
    above_LFC = False
    for i in range(len(p) - 1):
        p_mid = 0.5 * (p[i] + p[i+1])
        T_env = 0.5 * (T[i] + T[i+1])
        T_par = parcel_T(p_mid)
        dz = -Rd * T_env / (9.81 * p_mid) * (p[i+1] - p[i]) * 100.0
        buoy = 9.81 * (T_par - T_env) / T_env * dz
        if buoy > 0:
            CAPE += buoy
            above_LFC = True
        elif not above_LFC:
            CIN += buoy

    return CAPE, CIN, pL, TL

# ── tephigram coordinate transforms ──────────────────────────────────────────
# x = temperature on skew-T (°C + skew offset)
# y = log-pressure for plot y-axis
# We use a standard skew-T log-P layout (simpler than true tephigram,
# but meteorologically equivalent and far more readable)

SKEW  = 45.0   # degrees of skew (standard)

def skewx(T_C, p_hPa):
    """X position: temperature skewed by log(p)."""
    return T_C - SKEW * np.log(p_hPa / P0)

# ── parse all soundings ────────────────────────────────────────────────────────

def find_wmo(sta_name):
    """Match station name against UPPER_AIR_STATIONS, return wmo id or None."""
    norm = sta_name.lower().replace(",", "").strip()
    tokens = norm.split()
    if tokens and tokens[-1] in ("ua", "us"):
        tokens = tokens[:-1]
    norm = " ".join(tokens)
    for sta in UPPER_AIR_STATIONS:
        sta_norm = sta["name"].lower().replace(",", "").strip()
        if sta_norm == norm or sta_norm in norm or norm in sta_norm:
            return sta["wmo"]
    return None

def sounding_meta(geojson):
    p = geojson.get("properties", {})
    name = p.get("station_name", "Unknown")
    ts   = p.get("syn_timestamp") or p.get("firstSeen")
    if ts:
        dt = datetime.fromtimestamp(ts, tz=timezone.utc)
        time_str = dt.strftime("%Y-%m-%d %HZ")
        if dt.hour == 12:
            time_str += " [6AM MDT]"
        elif dt.hour == 0:
            time_str += " [6PM MDT]"
    else:
        time_str = "Unknown time"
    return name, time_str

def build_title(geojson, fallback_name, run):
    """Build a 'WMO_ID Station Name — Date HHZ [local time]' title, matching the wind-speed script."""
    try:
        sta_name, time_str = sounding_meta(geojson)
        wmo_id = find_wmo(sta_name)
        clean_name = sta_name
        clean_tokens = clean_name.split()
        if clean_tokens and clean_tokens[-1].lower() in ("ua", "us"):
            clean_name = " ".join(clean_tokens[:-1])
        clean_name = clean_name.rstrip(",").strip()
        title_name = f"{wmo_id} {clean_name}" if wmo_id else clean_name
        return f"{title_name} — {time_str}"
    except Exception:
        return f"{fallback_name}  [{run}]"

def parse_full(geojson):
    p, T, Td, u, v, h = [], [], [], [], [], []
    for feat in geojson.get("features", []):
        if feat["geometry"]["type"] != "Point":
            continue
        pr = feat["properties"]
        if any(pr.get(k) is None for k in ("pressure","temp","dewpoint","wind_u","wind_v","gpheight")):
            continue
        p.append(pr["pressure"])
        T.append(pr["temp"])        # K
        Td.append(pr["dewpoint"])   # K
        u.append(pr["wind_u"])
        v.append(pr["wind_v"])
        h.append(pr["gpheight"])
    arr = np.array
    return arr(p), arr(T), arr(Td), arr(u), arr(v), arr(h)

