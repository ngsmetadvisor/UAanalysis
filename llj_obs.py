def parse_sounding(geojson):
    """Extract pressure (hPa), height (m MSL), and wind speed (kt) from FM94 GeoJSON."""
    pres, wspd, height = [], [], []
    for feat in geojson.get("features", []):
        if feat["geometry"]["type"] != "Point":
            continue
        p  = feat["properties"]
        pr = p.get("pressure")
        u  = p.get("wind_u")
        v  = p.get("wind_v")
        h  = p.get("gpheight")
        if pr is None or u is None or v is None or h is None:
            continue
        spd_ms = np.sqrt(u**2 + v**2)
        spd_kt = spd_ms * 1.94384
        pres.append(pr)
        wspd.append(spd_kt)
        height.append(h)
    return np.array(pres), np.array(wspd), np.array(height)

def find_wmo(sta_name):
    """Match station name against UPPER_AIR_STATIONS, return wmo id or None."""
    norm = sta_name.lower().replace(",", "").strip()
    # strip trailing network/region tokens like "ua" or "us"
    tokens = norm.split()
    if tokens and tokens[-1] in ("ua", "us"):
        tokens = tokens[:-1]
    norm = " ".join(tokens)
    for sta in UPPER_AIR_STATIONS:
        sta_norm = sta["name"].lower().replace(",", "").strip()
        if sta_norm == norm or sta_norm in norm or norm in sta_norm:
            return sta["wmo"]
    return None

def sounding_meta(geojson):
    p = geojson.get("properties", {})
    name = p.get("station_name", "Unknown")
    ts   = p.get("syn_timestamp") or p.get("firstSeen")
    if ts:
        dt = datetime.fromtimestamp(ts, tz=timezone.utc)
        time_str = dt.strftime("%Y-%m-%d %HZ")
        if dt.hour == 12:
            time_str += " [6AM MDT]"
        elif dt.hour == 0:
            time_str += " [6PM MDT]"
    else:
        time_str = "Unknown time"
    return name, time_str

