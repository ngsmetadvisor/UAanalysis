def _match_raw_geojson_key(sta_name):
    """Find the raw_geojson top-level key that best matches a UPPER_AIR_STATIONS name."""
    target = _norm(sta_name)
    # exact match first
    for k in raw_geojson.keys():
        if _norm(k) == target:
            return k
    # fallback: substring match either direction
    for k in raw_geojson.keys():
        kn = _norm(k)
        if kn in target or target in kn:
            return k
    return None

